"""Nokia Groove G30 side of the declarative configuration: the client, the running configuration and the release rule.

See :mod:`orchestrator.optical.hal.reconcile`. The rule says how a path this module
applied is taken off a Groove G30 once no product block renders it any more.
"""

import re
from typing import Any, Final

from orchestrator.optical.hal.adapters.nokia_groove_g30._shared import get_g30_client
from orchestrator.optical.hal.reconcile import DeleteEntry, Reset, leaf_name, parent_name, split_instance_path

__all__ = ["get_g30_client", "release_rule", "running_config"]

#: Factory value of the leaves of a Groove G30 port or subport.
_PORT_RESETS: Final[dict[str, str]] = {
    "admin-status": "down",
    "service-label": "",
    "connected-to": "",
    "external-connectivity": "no",
    "port-mode": "not-applicable",
}


#: The containers of the running configuration read by :func:`running_config`.
_RUNNING_FIELDS: Final = (
    "/ne:ne/ne-id",
    "/ne:ne/ne-name",
    "/ne:ne/ne-location",
    "/ne:ne/ne-site",
    "/ne:ne/ne-altitude",
    "/ne:ne/shelf",
    "/ne:ne/inventory-data",
    "/ne:ne/services",
    "/ne:ne/system",
    "/ne:ne/protocols",
)

_CHM1: Final = "CHM1"
_CRS_PREFIX: Final = "/ne:ne/services/CRS["
_CRS_CHM1_LEAVES: Final = frozenset({"src-tp", "dst-tp", "alias-name"})
_SESSION_PREFIX: Final = "/ne:ne/system/security/session[session-id="

#: A shelf/slot reference, in instance keys (``shelf[shelf-id='1']/slot[slot-id='1']``) and in
#: termination point values (``ne:shelf[ne:shelf-id='1']/ne:slot[ne:slot-id='1']``).
_SLOT_REF: Final = re.compile(
    r"shelf\[(?:ne:)?shelf-id='(?P<shelf>[^']+)'\]/(?:ne:)?slot\[(?:ne:)?slot-id='(?P<slot>[^']+)'\]"
)


def running_config(client: Any) -> dict[str, Any]:
    """Return the running configuration of a Groove G30 as ``{path: value}``, without the leaves the device owns.

    Only the containers of :data:`_RUNNING_FIELDS` are read, and only the leaves the device
    reports (no defaults filled in). The device-owned leaves are left out, as they are not
    configuration anyone manages: the login sessions, the ODU types of the shelf, and the
    ``src-tp``, ``dst-tp`` and ``alias-name`` of a cross-connect with an endpoint on a CHM1
    card (generated by the device there).
    """
    config = client.data.retrieve(content="config", depth="unbounded", fields=list(_RUNNING_FIELDS))
    if config is None:
        return {}
    instances = config.model_dump_instances("/", content="config", exclude_unset=True)
    chm1_slots = _chm1_slots(instances)
    return {
        path: value
        for path, value in instances.items()
        if not path.startswith(_SESSION_PREFIX)
        and not (path.startswith("/ne:ne/shelf") and "odutype" in path)
        and not _is_chm1_crs_leaf(path, chm1_slots)
    }


def _chm1_slots(instances: dict[str, Any]) -> set[tuple[str, str]]:
    """Return the ``(shelf-id, slot-id)`` of the slots holding a CHM1 card."""
    slots: set[tuple[str, str]] = set()
    for path, value in instances.items():
        if path.endswith("/card/required-type") and value == _CHM1 and (match := _SLOT_REF.search(path)):
            slots.add((match["shelf"], match["slot"]))
    return slots


def _is_chm1_crs_leaf(path: str, chm1_slots: set[tuple[str, str]]) -> bool:
    """Whether ``path`` is a cross-connect leaf the device generates because an endpoint is on a CHM1."""
    if not path.startswith(_CRS_PREFIX) or path.rsplit("/", 1)[-1] not in _CRS_CHM1_LEAVES:
        return False
    return any((match["shelf"], match["slot"]) in chm1_slots for match in _SLOT_REF.finditer(path))


def release_rule(path: str) -> Reset | DeleteEntry | None:
    """Return how a released path is taken off a Groove G30.

    - A cross-connect is a list entry created by the orchestrator: it is deleted.
    - The leaves of a port or subport go back to their factory value. On a port of an
      ``OCC2`` subcard only the ``connected-to`` and ``service-label`` notes are cleared:
      the Open Line System ports stay in service.
    - Everything else is left alone: the optical channel and the ethernet facility of a
      port are removed by the device when the port mode is reset, and the amplifiers
      keep their settings.
    """
    segments = split_instance_path(path)
    for index, segment in enumerate(segments):
        if segment.startswith("CRS["):
            return DeleteEntry("/" + "/".join(segments[: index + 1]))
    if parent_name(path) not in {"port", "subport"}:
        return None
    leaf = leaf_name(path)
    if any(segment.startswith("subslot[") for segment in segments) and leaf not in {"connected-to", "service-label"}:
        return None
    return Reset(_PORT_RESETS[leaf]) if leaf in _PORT_RESETS else None
