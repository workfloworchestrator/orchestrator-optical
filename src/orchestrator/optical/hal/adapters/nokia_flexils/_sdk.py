"""The Nokia FlexILS SDK surface used by this adapter: the only module importing ``flexils_tl1``.

``flexils_tl1`` is the typed TL1 client generated by ``nokia-flexils-tl1-codegen``
(``flexils-tl1 generate``) from the vendor command reference. Every SDK name the adapter
needs is re-exported here, so that the SDK contract is explicit and a different SDK
(e.g. a client regenerated from a newer reference) is swapped in one place.
"""

from orchestrator.optical.hal._common import VendorSdkNotInstalledError

try:
    from flexils_tl1.base import (
        BaseRequest,
        BaseResponse,
    )
    from flexils_tl1.client import (
        FlexSdkClientBase,
    )
    from flexils_tl1.errors import (
        TL1DeniedError,
    )
    from flexils_tl1.generated.methods import (
        GeneratedMethods,
    )
    from flexils_tl1.protocol.parser import (
        parse_reply,
    )
    from flexils_tl1.transport.ssh import (
        SshTransport,
    )
except ModuleNotFoundError as exc:
    raise VendorSdkNotInstalledError(sdk="flexils_tl1", device="Nokia FlexILS") from exc

__all__ = [
    "BaseRequest",
    "BaseResponse",
    "FlexSdkClientBase",
    "GeneratedMethods",
    "SshTransport",
    "TL1DeniedError",
    "parse_reply",
]
